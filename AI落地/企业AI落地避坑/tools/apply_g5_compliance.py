#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""第5组：第七章合规 9 处。5.1 七处去标记改通用要求/模板；5.2 两处按推荐。"""
import sys

P = 'AI未成之路_定稿候选版_v1.23_20261107.md'
lines = open(P, encoding='utf-8').read().split('\n')
ok, fail = [], []


def rep(must, old, new, tag):
    """唯一定位行，做子串替换。"""
    global lines
    idx = [i for i, l in enumerate(lines) if must in l]
    if len(idx) != 1:
        fail.append((tag, f'命中{len(idx)}处: {must[:45]}'))
        return
    i = idx[0]
    if old not in lines[i]:
        fail.append((tag, f'子串未找到: {old[:45]}'))
        return
    lines[i] = lines[i].replace(old, new)
    ok.append(f'{tag} @L{i+1}')


# ── 5.1 七处：去掉【待核实】，改通用要求 / 模板 ──
rep('在受控场景里（受监管行业对计算机化系统的合规要求所覆盖的场景',
    '在受控场景里（受监管行业对计算机化系统的合规要求所覆盖的场景【待核实】）',
    '在受控场景里（受监管行业对计算机化系统的合规要求所覆盖的场景）', '5.1-7.1a')
rep('| L4 受控级 | 涉及受监管场景下的受控数据与受控文档 |',
    '需质量部门单独批准【待核实】', '需质量部门单独批准', '5.1-7.1b')
rep('受监管场景下的受控数据（关键工艺参数、批次生产记录',
    '受监管场景下的受控数据（关键工艺参数、批次生产记录、检验数据、偏差与质量事件记录）【待核实】',
    '受监管场景下的受控数据（关键工艺参数、批次生产记录、检验数据、偏差与质量事件记录）', '5.1-7.2a')
rep('制药场景里数据与记录保存有明确年限要求',
    '制药场景里数据与记录保存有明确年限要求【待核实】',
    '受监管场景里数据与记录保存有明确年限要求', '5.1-7.3a')
rep('**日志留存与可导出** | 留存期限（不少于企业业务数据保存要求',
    '留存期限（不少于企业业务数据保存要求【待核实】）',
    '留存期限（不少于企业业务数据保存要求）', '5.1-7.5a')
rep('抽样引用缺失率超阈值',
    '抽样引用缺失率超阈值【待核实】', '抽样引用缺失率超过设定阈值', '5.1-7.6a')
rep('供应商留存期 < 企业追溯期',
    '供应商留存期 < 企业追溯期【待核实】', '供应商留存期 < 企业追溯期', '5.1-7.6b')

# ── 5.2 ① 置信度 85% ──
rep('素材里出现过"置信度低于 85% 自动触发人工复核"的写法',
    '素材里出现过"置信度低于 85% 自动触发人工复核"的写法，也有通过法规知识库检索增强压低幻觉率的做法【待核实】——这些数字要确认是否实测。',
    '素材里出现过"置信度低于 85% 自动触发人工复核"的写法，也有通过法规知识库检索增强压低幻觉率的做法——★ **但 85% 只是素材中出现过的一个量级，★★ 不是可以直接抄进自己项目的实测值**：★ **阈值必须按自己的场景标定**，★ ★ ★ 而标定的依据只能是"★ **错一次的代价有多大**"，★ ★ 不可能是"别人的项目用了多少"。',
    '5.2-7.4阈值')

# ── 5.2 ② 知识库更新节奏（泛化 + 注明可选做法）──
rep('公开医学与药品知识库采用"每日增量 + 季度全量 + 高风险知识由专业人员复核"的组合',
    '公开医学与药品知识库采用"每日增量 + 季度全量 + 高风险知识由专业人员复核"的组合【待核实】——值得抄到任何依赖外部知识的场景。',
    '公开专业知识库常见的一种做法是"每日增量 + 季度全量 + 高风险知识由专业人员复核"——★ **这是一种可选做法，不是唯一标准**，★ ★ 但它值得抄到任何依赖外部知识的场景。',
    '5.2-7.2知识库')

open(P, 'w', encoding='utf-8').write('\n'.join(lines))
print(f'✅ {len(ok)}/{len(ok)+len(fail)}')
for x in ok:
    print('   ', x)
if fail:
    print(f'\n❌ {len(fail)}:')
    for tag, o in fail:
        print(f'   [{tag}] {o}')
    sys.exit(1)
