def ed(must, new, tag, expect=1):
    """定位包含 must 的行（须唯一），替换或删除。"""
    global lines
    idx = [i for i, l in enumerate(lines) if must in l]
    if len(idx) != expect:
        fail.append((tag, f'命中 {len(idx)} 处（期望{expect}）: {must[:50]}'))
        return
    i = idx[0]
    if new is None:
        del lines[i]
    else:
        lines[i] = new
    ok.append(f'{tag} @L{i+1}')


def rep_in(must, old, new, tag):
    """在包含 must 的行内做子串替换。"""
    global lines
    idx = [i for i, l in enumerate(lines) if must in l]
    if len(idx) != 1:
        fail.append((tag, f'命中 {len(idx)} 处: {must[:50]}'))
        return
    i = idx[0]
    if old not in lines[i]:
        fail.append((tag, f'子串未找到: {old[:40]}'))
        return
    lines[i] = lines[i].replace(old, new)
    ok.append(f'{tag} @L{i+1}')


